"""Generate `app_backend/eligibility_extracted.py` from `mec_crosswalk.json`.

This writes the machine-extracted half of the eligibility matrix. It is kept in
a separate generated module so the hand-curated entries in `eligibility_data.py`
-- and the documentation explaining why they were transcribed by hand -- are
never overwritten. `eligibility_data.py` imports this and lets its own
hand-verified entries win on any id present in both.

Only crosswalk states `verified` and `extracted` are emitted. `needs_review` and
`unmapped` produce nothing at all, so an ambiguous identity can never reach a
user no matter what this script is run against.

Provenance is carried per condition, not per rating, and is the whole point of
the split:

  hand_verified          - a person checked it against the printed WHO page
  extracted_pending_review - a script matched the labels; nobody has confirmed
                             that the two labels denote the same condition

Run:  python tool/build_matrix.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
XWALK = ROOT / "mec_crosswalk.json"
REG = ROOT / "mec_registry.json"
OUT = (ROOT.parent / "pcos_ml_project" / "app_backend"
       / "eligibility_extracted.py")

SERVABLE = {"verified", "extracted"}
PROVENANCE = {"verified": "hand_verified", "extracted": "extracted_pending_review"}


def as_category(value):
    """Normalize an extracted category to an int 1-4, or None if unusable.

    The extraction stores WHO's cells as the strings it printed ("1", "4").
    Those are converted. Anything else is refused rather than coerced:
      "NA"      - not applicable, which is NOT the same as category 1
      "2/3"     - a genuine WHO composite; picking either half would be a guess
      "" / None - nothing printed
    """
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value if 1 <= value <= 4 else None
    text = str(value).strip()
    if text.isdigit():
        n = int(text)
        return n if 1 <= n <= 4 else None
    return None


def main():
    xwalk = json.loads(XWALK.read_text(encoding="utf-8"))
    reg = {c["id"]: c for c in json.loads(REG.read_text(encoding="utf-8"))["conditions"]}

    out, skipped, phase_conflicts = [], [], []
    for cond in xwalk["conditions"]:
        cid, state = cond["id"], cond["state"]
        if state not in SERVABLE:
            continue
        if cid not in reg:
            skipped.append((cid, "not in registry"))
            continue

        wants_cont = cond.get("init_cont") == "continuation"
        categories = {}
        for method, phases in cond["ratings"].items():
            if "I" in phases and "C" in phases:
                if phases["I"]["category"] != phases["C"]["category"]:
                    # Initiation and continuation genuinely differ. A single
                    # per-method cell cannot express that, so it is reported
                    # rather than silently collapsed to one of them.
                    phase_conflicts.append(
                        f"{cid}[{method}]: I={phases['I']['category']} "
                        f"C={phases['C']['category']}")
                    continue
            cell = phases.get("C" if wants_cont else "I")
            if cell is None:
                continue
            cat = as_category(cell["category"])
            # A composite such as "2/3" or "NA" is not a backend category. The
            # backend serves ints 1-4 only, so it is dropped and reported
            # instead of being coerced into one of its halves.
            if cat is None:
                skipped.append(
                    (cid, f"{method}: unusable category {cell['category']!r}"))
                continue
            categories[method] = cat

        if not categories:
            skipped.append((cid, "no usable integer category"))
            continue
        out.append({"id": cid, "label": cond["label"],
                    "provenance": PROVENANCE[state],
                    "categories": categories})

    out.sort(key=lambda r: r["id"])
    lines = [
        '"""Machine-extracted WHO MEC ratings. GENERATED by tool/build_matrix.py.',
        "",
        "Do not edit by hand: rerun the generator instead. Anything hand-checked",
        "against the printed WHO MEC 5th-edition pages belongs in",
        "`eligibility_data.py`, which overrides every id present in both files.",
        "",
        "Each entry records HOW its identity was established:",
        '  hand_verified            - checked by a person against the printed page',
        "  extracted_pending_review - matched by script; a clinician has NOT",
        "                            confirmed the two labels denote the same",
        "                            condition. Surfaced as such in the app.",
        "",
        "Categories are copied verbatim from the extracted WHO table cell. No",
        "value here is inferred, averaged, or filled in by inference.",
        '"""',
        "",
        "EXTRACTED_CONDITIONS: list[dict] = [",
    ]
    for row in out:
        cats = ", ".join(f'"{m}": {v}' for m, v in sorted(row["categories"].items()))
        lines.append("    {")
        lines.append(f'        "id": {row["id"]!r},')
        lines.append(f'        "label": {row["label"]!r},')
        lines.append(f'        "provenance": {row["provenance"]!r},')
        lines.append(f'        "categories": {{{cats}}},')
        lines.append("    },")
    lines += [
        "]",
        "",
        f"# {len(out)} conditions, "
        f"{sum(len(r['categories']) for r in out)} method cells.",
        "# generated_by: tool/build_matrix.py",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")

    hand = sum(1 for r in out if r["provenance"] == "hand_verified")
    print(f"wrote {OUT}")
    print(f"  conditions : {len(out)}  "
          f"(hand_verified {hand}, extracted_pending_review {len(out) - hand})")
    print(f"  method cells: {sum(len(r['categories']) for r in out)}")
    if phase_conflicts:
        print(f"\n  {len(phase_conflicts)} method(s) differ between initiation "
              f"and continuation and were NOT emitted:")
        for line in phase_conflicts[:10]:
            print(f"    {line}")
    if skipped:
        print(f"\n  {len(skipped)} servable condition(s) produced no usable cell:")
        for cid, why in skipped[:10]:
            print(f"    {cid}: {why}")


if __name__ == "__main__":
    sys.exit(main())
